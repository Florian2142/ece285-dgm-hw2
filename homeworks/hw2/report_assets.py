"""Put one run's figures and numbers into the HW2 report (homeworks/hw2/report/generated/).

    uv run python -m hw2.report_assets                 # latest run
    uv run python -m hw2.report_assets --run <name>    # a specific run
    uv run python -m hw2.report_assets --placeholder   # reset to placeholders (no run needed)

Writes loss_curves.pdf, samples.png, interpolation.png, real.png, hparams.tex, results.tex,
and source.txt. The report \\input's these files, so rebuilding the PDF shows the chosen run.
Run ``python -m hw2.evaluate`` first; without its scores the numbers stay "??".
"""

from __future__ import annotations

import argparse
import math
import shutil
from datetime import date
from pathlib import Path

from dgm.data.wikiart import processed_dir
from dgm.training.loggers import read_csv
from dgm.training.runs import read_json, resolve_run_dir
from dgm.utils.config import load_config
from dgm.utils.viz import plot_metric_panels
from hw2.config import Config
from hw2.train import CURVES, DEFAULT_CONFIG, EXPERIMENT

GENERATED = Path(__file__).parent / "report" / "generated"
PLACEHOLDER = r"\textcolor{red}{??}"
IMAGES = ("samples.png", "interpolation.png", "real.png")
# Score macros: Result<score><row>. Rows: samples (mean +- std over repeats) and real
# training paintings. Scores: FID (tutorial / ignite default), FIDpool (2048-d), IS.
SCORE_MACROS = {"fid": "FID", "fid_2048": "FIDpool", "inception_score": "IS"}
ROWS = {"samples": "", "real_train_images": "real"}
MACROS = (
    *(f"Result{score}{row}" for row in ROWS.values() for score in SCORE_MACROS.values()),
    "ResultNumSamples",
    "ResultRepeats",
    "ResultWeights",
    "ResultBestEpoch",
    "ResultValFID",
    "ResultParamsG",
    "ResultParamsD",
    "ResultTrainTime",
    "ResultTrainImages",
    "ResultValImages",
    "ResultTestImages",
)


def latex_number(x: float) -> str:
    """1e-3 -> 10^{-3}, 2e-4 -> 2\\times10^{-4}, 0.5 -> 0.5 (for use in math mode)."""
    if x == 0:
        return "0"
    exponent = math.floor(math.log10(abs(x)))
    mantissa = x / 10**exponent
    if -2 <= exponent <= 3:
        return f"{x:g}"
    if math.isclose(mantissa, 1.0):
        return f"10^{{{exponent}}}"
    return f"{mantissa:g}\\times10^{{{exponent}}}"


def decimals(value: float) -> int:
    """Digits that suit both scales: tutorial FID (< 1) and FID-2048 (tens to hundreds)."""
    return 4 if abs(value) < 1 else 2 if abs(value) < 100 else 1


def number(value: float) -> str:
    return f"{value:.{decimals(value)}f}"


def pm(summary: dict) -> str:
    """``mean \\pm std`` with the decimals of the mean for both numbers."""
    d = decimals(summary["mean"])
    return f"\\ensuremath{{{summary['mean']:.{d}f} \\pm {summary['std']:.{d}f}}}"


def millions(count: int | None) -> str:
    return f"{count / 1e6:.2f}\\,M" if count else PLACEHOLDER


def hparams_tex(cfg: Config, env: dict, best_epoch: int | None) -> str:
    m, t, d = cfg.model, cfg.train, cfg.data
    lr = (
        f"${latex_number(t.lr_g)}$"
        if t.lr_g == t.lr_d
        else f"G ${latex_number(t.lr_g)}$, D ${latex_number(t.lr_d)}$"
    )
    rows = [
        ("Image size", f"${d.image_size}\\times{d.image_size}$, RGB, $[-1,1]$"),
        ("Styles", ", ".join(s.replace("_", " ") for s in d.styles) if d.styles else "all 27"),
        ("Latent $\\vz$", f"$\\Normal(\\bm 0,\\mI_{{{m.latent_dim}}})$"),
        ("Width G / D", f"{m.g_channels} / {m.d_channels}"),
        (
            "Parameters G / D",
            f"{millions(env.get('parameters_generator'))} / {millions(env.get('parameters_discriminator'))}",
        ),
        ("Loss", t.loss),
        ("Optimizer", f"Adam, $\\beta=({t.beta1:g}, {t.beta2:g})$"),
        ("Learning rate", lr),
        ("Batch size", str(d.batch_size)),
        ("Epochs (best)", f"{t.epochs} ({best_epoch if best_epoch else PLACEHOLDER})"),
        ("EMA of weights", f"decay {t.ema_decay:g}" if t.ema_decay else "none"),
        ("Augmentation", "horizontal flips" if t.hflip else "none"),
        ("Initialization", m.init),
        ("Seed", str(t.seed)),
    ]
    # Two name/value pairs per line keep the table short (2-page report).
    half = (len(rows) + 1) // 2
    left, right = rows[:half], rows[half:] + [("", "")] * (2 * half - len(rows))
    lines = [
        "% Generated by `python -m hw2.report_assets`. Do not edit by hand.",
        "\\begin{tabular}{@{}ll@{\\hspace{2em}}ll@{}}",
        "\\toprule",
        *(f"{a} & {b} & {c} & {e} \\\\" for (a, b), (c, e) in zip(left, right, strict=True)),
        "\\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def results_tex(values: dict[str, str], source: str) -> str:
    lines = [
        "% Generated by `python -m hw2.report_assets`. Do not edit by hand.",
        f"% Source: {source}",
    ]
    lines += [f"\\newcommand{{\\{name}}}{{{values.get(name, PLACEHOLDER)}}}" for name in MACROS]
    return "\n".join(lines) + "\n"


def dataset_counts(cfg: Config, env: dict) -> dict[str, str]:
    """Image counts of the run (env.json), else of the prepared data (meta.json)."""
    counts = dict(env.get("images", {}))
    meta_path = processed_dir(cfg.data.image_size) / "meta.json"
    if meta_path.exists():
        meta = read_json(meta_path)["counts"]
        for split in ("train", "val", "test"):
            counts.setdefault(
                split,
                sum(meta[split][s] for s in cfg.data.styles)
                if cfg.data.styles
                else meta[split]["total"],
            )
    names = {"train": "ResultTrainImages", "val": "ResultValImages", "test": "ResultTestImages"}
    return {names[split]: f"{count:,}" for split, count in counts.items() if split in names}


def write(name: str, text: str) -> None:
    (GENERATED / name).write_text(text, encoding="utf-8", newline="\n")


def write_placeholders() -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name in ("loss_curves.pdf", "loss_curves.png", *IMAGES):
        (GENERATED / name).unlink(missing_ok=True)
    cfg = load_config(Config, DEFAULT_CONFIG)
    write("hparams.tex", hparams_tex(cfg, {}, None))
    write("results.tex", results_tex(dataset_counts(cfg, {}), "placeholders (no run selected yet)"))
    write("source.txt", "placeholders: no run selected yet\n")
    print(f"reset {GENERATED} to placeholders")


def export(run_dir: Path) -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    cfg = load_config(Config, run_dir / "config.yaml")
    env = read_json(run_dir / "env.json") if (run_dir / "env.json").exists() else {}
    summary = read_json(run_dir / "summary.json") if (run_dir / "summary.json").exists() else {}
    metrics_path = run_dir / "eval" / "metrics.json"
    scores = read_json(metrics_path) if metrics_path.exists() else {}

    plot_metric_panels(read_csv(run_dir / "metrics.csv"), GENERATED / "loss_curves", CURVES)
    for name in IMAGES:
        src = run_dir / "eval" / name
        if src.exists():
            shutil.copy2(src, GENERATED / name)
        else:
            (GENERATED / name).unlink(missing_ok=True)

    values = dataset_counts(cfg, env)
    if summary:
        values["ResultBestEpoch"] = str(summary["best_epoch"])
        values["ResultTrainTime"] = f"{summary['train_time_s'] / 60:.0f}\\,min"
        if summary.get("best_val_fid_2048") is not None:
            values["ResultValFID"] = number(summary["best_val_fid_2048"])
    if env.get("parameters_generator"):
        values["ResultParamsG"] = millions(env["parameters_generator"])
        values["ResultParamsD"] = millions(env["parameters_discriminator"])
    if "samples" in scores:
        values["ResultNumSamples"] = f"{scores['num_samples']:,}"
        values["ResultRepeats"] = str(scores["repeats"])
        values["ResultWeights"] = "EMA" if scores.get("weights") == "ema" else "raw"
        for row_key, row in ROWS.items():
            for score_key, score in SCORE_MACROS.items():
                if row_key == "samples":
                    values[f"Result{score}"] = pm(scores["samples"][score_key])
                elif row_key in scores:
                    values[f"Result{score}{row}"] = number(scores[row_key][score_key])

    source = (
        f"{run_dir.name} (git {env.get('git') or 'unknown'}), exported {date.today().isoformat()}"
    )
    write("hparams.tex", hparams_tex(cfg, env, summary.get("best_epoch")))
    write("results.tex", results_tex(values, source))
    write("source.txt", source + "\n")
    missing = [name for name in MACROS if name not in values]
    print(f"exported {run_dir.name} -> {GENERATED}")
    if missing:
        print(
            f"still placeholders: {', '.join(missing)}"
            + ("" if scores else "  (run: uv run python -m hw2.evaluate)")
        )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--run", default="latest", help="run name or folder under runs/hw2 (default: latest)"
    )
    parser.add_argument(
        "--placeholder", action="store_true", help="reset the report to placeholders"
    )
    args = parser.parse_args(argv)
    if args.placeholder:
        write_placeholders()
        return
    try:
        export(resolve_run_dir(EXPERIMENT, args.run))
    except FileNotFoundError as err:
        raise SystemExit(f"error: {err}") from None


if __name__ == "__main__":
    main()
